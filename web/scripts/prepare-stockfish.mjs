// Prepares the lite single-threaded Stockfish build (≈1.8MB) for both runtimes:
//
// 1. Browser: copies the worker script + .wasm into public/stockfish/ so Vite serves them.
//    Single-threaded needs no COOP/COEP headers.
// 2. Convex (Node actions): writes vendor/stockfish/ — a patched copy of the engine glue that
//    takes its .wasm bytes from a global instead of reading a file next to itself, plus the
//    .wasm as a base64 module. Convex bundles both like ordinary code. (The stockfish npm
//    package is ~200MB, too big to install as a Convex external package.)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ENGINE = 'stockfish-19-lite-single';
const require = createRequire(import.meta.url);
const binDir = join(dirname(require.resolve('stockfish/package.json')), 'bin');
const webDir = join(dirname(fileURLToPath(import.meta.url)), '..');

const publicDir = join(webDir, 'public', 'stockfish');
mkdirSync(publicDir, { recursive: true });
for (const ext of ['.js', '.wasm']) {
  copyFileSync(join(binDir, ENGINE + ext), join(publicDir, ENGINE + ext));
}

// Patches to the glue's Node code path. Each must match exactly once; if a stockfish release
// changes the glue, this fails loudly instead of shipping a broken engine.
const PATCHES = [
  {
    why: 'take the .wasm bytes from a global instead of reading a file next to the script',
    from: 't=r.join(__dirname,r.basename(__filename,r.extname(__filename))+".wasm"),i={locateFile:',
    to: 't=r.join(__dirname,r.basename(__filename,r.extname(__filename))+".wasm"),i={get wasmBinary(){return globalThis.__STOCKFISH_WASM__},locateFile:',
  },
  {
    why: 'do not set the global fetch to null (Convex actions need fetch to call mutations)',
    from: '}),fetch=null),r.print=',
    to: '})),r.print=',
  },
];

let patched = readFileSync(join(binDir, `${ENGINE}.js`), 'utf8');
for (const { why, from, to } of PATCHES) {
  if (patched.split(from).length !== 2) {
    throw new Error(`prepare-stockfish: can't apply patch (${why}); the glue in ${ENGINE}.js changed`);
  }
  patched = patched.replace(from, to);
}

const vendorDir = join(webDir, 'vendor', 'stockfish');
mkdirSync(vendorDir, { recursive: true });
writeFileSync(join(vendorDir, 'engine.cjs'), patched);
writeFileSync(
  join(vendorDir, 'engine.d.cts'),
  `// Generated by scripts/prepare-stockfish.mjs — do not edit.
declare function createEngine(): {
  processCommand(command: string): void;
  listener?: (line: string) => void;
};
export = createEngine;
`,
);
writeFileSync(
  join(vendorDir, 'wasm.ts'),
  `// Generated by scripts/prepare-stockfish.mjs from ${ENGINE}.wasm — do not edit.\n` +
    `export const STOCKFISH_WASM_BASE64 =\n  '${readFileSync(join(binDir, `${ENGINE}.wasm`)).toString('base64')}';\n`,
);
